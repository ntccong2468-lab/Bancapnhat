  const env=envSetup({REQUIRE_EMAIL_VERIFICATION:'1',EMAIL_FROM:'no-reply@vncode.example',PUBLIC_BASE_URL:'https://vncode.example',EMAIL:{send:async(msg)=>{sent.push(msg);return {messageId:'fake'}}}});
